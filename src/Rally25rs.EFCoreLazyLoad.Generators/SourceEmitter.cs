using System.Text;

namespace Rally25rs.EFCoreLazyLoad.Generators;

/// <summary>Renders a <see cref="TypeModel"/> as C# source.</summary>
internal static class SourceEmitter
{
    private const string LoaderType = "global::Microsoft.EntityFrameworkCore.Infrastructure.ILazyLoader";
    private const string LoadMethod = "global::Microsoft.EntityFrameworkCore.Infrastructure.LazyLoaderExtensions.Load";

    public static string Emit(TypeModel model)
    {
        var sb = new StringBuilder();
        sb.AppendLine("// <auto-generated/>");
        sb.AppendLine("#nullable enable");
        sb.AppendLine();

        if (model.Namespace is not null)
        {
            sb.Append("namespace ").Append(model.Namespace).AppendLine(";");
            sb.AppendLine();
        }

        var indent = 0;
        foreach (var outer in model.ContainingTypes)
        {
            OpenType(sb, indent, outer.Keyword, outer.NameWithTypeParameters);
            indent++;
        }

        OpenType(sb, indent, model.Keyword, model.NameWithTypeParameters);
        indent++;
        var pad = new string(' ', indent * 4);
        var first = true;

        if (model.LoaderFieldAccessibility is not null)
        {
            // EF Core assigns this through service-property injection, never from user code.
            sb.Append(pad).AppendLine("[global::System.Text.Json.Serialization.JsonIgnore]");
            sb.AppendLine("#pragma warning disable CS0649");
            sb.Append(pad).Append(model.LoaderFieldAccessibility).Append(' ').Append(LoaderType).Append("? ")
                .Append(model.LoaderMemberName).AppendLine(";");
            sb.AppendLine("#pragma warning restore CS0649");
            first = false;
        }

        foreach (var property in model.Properties)
        {
            if (!first)
            {
                sb.AppendLine();
            }

            first = false;
            sb.Append(pad).Append(property.Modifiers).Append(' ').Append(property.Type).Append(' ')
                .AppendLine(property.Name);
            sb.Append(pad).AppendLine("{");

            if (property.BackingFieldReturn is not null)
            {
                // Get-only over a declared backing field: EF fills the field; we only trigger the load.
                sb.Append(pad).Append("    ");
                AppendAccessorModifiers(sb, property.Getter);
                sb.AppendLine("get");
                sb.Append(pad).AppendLine("    {");
                sb.Append(pad).Append("        ").Append(model.LoaderMemberName).Append("?.Load(this, nameof(")
                    .Append(property.Name).AppendLine("));");
                sb.Append(pad).Append("        return ").Append(property.BackingFieldReturn).AppendLine(";");
                sb.Append(pad).AppendLine("    }");
                sb.Append(pad).AppendLine("}");
                continue;
            }

            // The `field` backing store is inferred nullable (the getter tolerates null), so a
            // non-nullable navigation only needs `!` on the returned value.
            sb.Append(pad).Append("    ");
            AppendAccessorModifiers(sb, property.Getter);
            sb.Append("get => ").Append(LoadMethod).Append('(').Append(model.LoaderMemberName)
                .Append(", this, ref field, nameof(").Append(property.Name).Append("))")
                .Append(property.IsNullable ? "" : "!").AppendLine(";");

            if (property.Setter is not null)
            {
                sb.Append(pad).Append("    ");
                AppendAccessorModifiers(sb, property.Setter);
                sb.Append(property.Setter.Keyword).AppendLine(" => field = value;");
            }

            sb.Append(pad).AppendLine("}");
        }

        for (var i = indent - 1; i >= 0; i--)
        {
            sb.Append(new string(' ', i * 4)).AppendLine("}");
        }

        return sb.ToString();
    }

    private static void OpenType(StringBuilder sb, int indent, string keyword, string name)
    {
        var pad = new string(' ', indent * 4);
        sb.Append(pad).Append("partial ").Append(keyword).Append(' ').AppendLine(name);
        sb.Append(pad).AppendLine("{");
    }

    private static void AppendAccessorModifiers(StringBuilder sb, AccessorModel accessor)
    {
        if (accessor.Modifiers.Length > 0)
        {
            sb.Append(accessor.Modifiers).Append(' ');
        }
    }
}
