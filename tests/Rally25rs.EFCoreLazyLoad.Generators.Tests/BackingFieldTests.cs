using Microsoft.CodeAnalysis;

namespace Rally25rs.EFCoreLazyLoad.Generators.Tests;

/// <summary>
///     Get-only partial navigations over a declared backing field: the DDD read-only collection pattern.
/// </summary>
public class BackingFieldTests
{
    private const string Prelude = """
        using System.Collections.Generic;
        using System.Collections.ObjectModel;
        using Rally25rs.EFCoreLazyLoad;

        namespace Shop;

        public class Line { public int Id { get; set; } }

        """;

    [Fact]
    public void ReadOnlyCollection_OverListField_LoadsThenReturnsAsReadOnly()
    {
        var result = GeneratorHarness.RunClean(Prelude + """
            [LazyLoad]
            public partial class Order
            {
                private readonly List<Line> _lines = [];
                public partial IEnumerable<Line> Lines { get; }
                public void AddLine(Line line) => _lines.Add(line);
            }
            """);

        Assert.Equal(
            """
            // <auto-generated/>
            #nullable enable

            namespace Shop;

            partial class Order
            {
                [global::System.Text.Json.Serialization.JsonIgnore]
            #pragma warning disable CS0649
                protected global::Microsoft.EntityFrameworkCore.Infrastructure.ILazyLoader? __lazyLoader;
            #pragma warning restore CS0649

                public partial global::System.Collections.Generic.IEnumerable<global::Shop.Line> Lines
                {
                    get
                    {
                        __lazyLoader?.Load(this, nameof(Lines));
                        return this._lines.AsReadOnly();
                    }
                }
            }

            """.ReplaceLineEndings(),
            result.GeneratedSource("Shop.Order.LazyLoad.g.cs").ReplaceLineEndings());
    }

    [Theory]
    [InlineData("IReadOnlyCollection<Line>")]
    [InlineData("IReadOnlyList<Line>")]
    [InlineData("ReadOnlyCollection<Line>")]
    public void ReadOnlyCollectionTypes_UseAsReadOnly(string propertyType)
    {
        var result = GeneratorHarness.RunClean(Prelude + $$"""
            [LazyLoad]
            public partial class Order
            {
                private readonly List<Line> _lines = [];
                public partial {{propertyType}} Lines { get; }
            }
            """);

        Assert.Contains("return this._lines.AsReadOnly();", result.GeneratedSource("Shop.Order.LazyLoad.g.cs"));
    }

    [Theory]
    [InlineData("_lines")]
    [InlineData("_Lines")]
    [InlineData("m_lines")]
    [InlineData("m_Lines")]
    [InlineData("lines")]
    public void BackingField_IsFoundByEFCoreNamingConventions(string fieldName)
    {
        var result = GeneratorHarness.RunClean(Prelude + $$"""
            [LazyLoad]
            public partial class Order
            {
                private readonly List<Line> {{fieldName}} = [];
                public partial IEnumerable<Line> Lines { get; }
            }
            """);

        Assert.Contains($"return this.{fieldName}.AsReadOnly();", result.GeneratedSource("Shop.Order.LazyLoad.g.cs"));
    }

    [Fact]
    public void FieldWithoutAsReadOnly_IsReturnedDirectly()
    {
        var result = GeneratorHarness.RunClean(Prelude + """
            [LazyLoad]
            public partial class Order
            {
                private readonly HashSet<Line> _lines = [];
                public partial IEnumerable<Line> Lines { get; }
            }
            """);

        Assert.Contains("return this._lines;", result.GeneratedSource("Shop.Order.LazyLoad.g.cs"));
    }

    [Fact]
    public void NullableField_IsNullSafe_AndSuppressedForNonNullableProperty()
    {
        var result = GeneratorHarness.RunClean(Prelude + """
            [LazyLoad]
            public partial class Order
            {
                private List<Line>? _lines;
                public partial IReadOnlyCollection<Line> Lines { get; }
                public void AddLine(Line line) => (_lines ??= []).Add(line);
            }
            """);

        Assert.Contains("return this._lines?.AsReadOnly()!;", result.GeneratedSource("Shop.Order.LazyLoad.g.cs"));
    }

    [Fact]
    public void ReferenceNavigation_OverBackingField_IsSupported()
    {
        var result = GeneratorHarness.RunClean(Prelude + """
            [LazyLoad]
            public partial class Order
            {
                private Line? _primaryLine;
                public partial Line PrimaryLine { get; }
                public void SetPrimary(Line line) => _primaryLine = line;
            }
            """);

        Assert.Contains("return this._primaryLine!;", result.GeneratedSource("Shop.Order.LazyLoad.g.cs"));
    }

    [Fact]
    public void PropertyWithSetter_StillUsesFieldKeyword()
    {
        // Only get-only properties switch to the declared field; with a setter the property owns its storage.
        var result = GeneratorHarness.RunClean(Prelude + """
            [LazyLoad]
            public partial class Order
            {
                private readonly List<Line> _lines = [];
                public partial List<Line> Lines { get; set; }
            }
            """);

        Assert.Contains("ref field, nameof(Lines))!;", result.GeneratedSource("Shop.Order.LazyLoad.g.cs"));
    }

    [Fact]
    public void GetOnlyWithoutBackingField_StillUsesFieldKeyword()
    {
        var result = GeneratorHarness.RunClean(Prelude + """
            [LazyLoad]
            public partial class Order
            {
                public partial List<Line> Lines { get; }
            }
            """);

        Assert.Contains("ref field, nameof(Lines))!;", result.GeneratedSource("Shop.Order.LazyLoad.g.cs"));
    }

    [Fact]
    public void EFLL009_IncompatibleBackingField()
    {
        var result = GeneratorHarness.Run(Prelude + """
            [LazyLoad]
            public partial class Order
            {
                private readonly List<string> _lines = [];
                public partial IEnumerable<Line> Lines { get; }
            }
            """);

        var diagnostic = Assert.Single(result.GeneratorDiagnostics);
        Assert.Equal("EFLL009", diagnostic.Id);
        Assert.Equal(DiagnosticSeverity.Error, diagnostic.Severity);
        Assert.Contains("'_lines'", diagnostic.GetMessage());
    }

    [Fact]
    public void EFLL010_NonPartialReadOnlyCollection_InLazyLoadClass_Warns()
    {
        // The hand-written pattern compiles, but its getter never asks the loader to load.
        var result = GeneratorHarness.Run(Prelude + """
            [LazyLoad]
            public partial class Order
            {
                private readonly List<Line> _lines = [];
                public IEnumerable<Line> Lines => _lines.AsReadOnly();
            }
            """);

        var diagnostic = Assert.Single(result.GeneratorDiagnostics);
        Assert.Equal("EFLL010", diagnostic.Id);
        Assert.Equal(DiagnosticSeverity.Warning, diagnostic.Severity);
        Assert.Contains("Shop.Order.Lines", diagnostic.GetMessage());
        Assert.Contains("'_lines'", diagnostic.GetMessage());
    }

    [Theory]
    [InlineData("private readonly List<string> _tags = []; public IEnumerable<string> Tags => _tags;")]
    [InlineData("private string _name = \"\"; public string Name => _name;")]
    [InlineData("private Line? _line; public Line? Line => _line;")]
    [InlineData("private readonly List<Line> _lines = []; public IEnumerable<Line> Lines { get => _lines; set { } }")]
    [InlineData("public IEnumerable<Line> Lines => [];")]
    public void EFLL010_IsNotReported_ForOtherMembers(string members)
    {
        var result = GeneratorHarness.Run(Prelude + $$"""
            [LazyLoad]
            public partial class Order
            {
                {{members}}
            }
            """);

        Assert.Empty(result.GeneratorDiagnostics);
    }

    [Fact]
    public void EFLL010_IsNotReported_WithoutClassLevelAttribute()
    {
        var result = GeneratorHarness.Run(Prelude + """
            public partial class Order
            {
                private readonly List<Line> _lines = [];
                public IEnumerable<Line> Lines => _lines.AsReadOnly();
                [LazyLoad] public partial Line Primary { get; set; }
            }
            """);

        Assert.Empty(result.GeneratorDiagnostics);
    }
}
