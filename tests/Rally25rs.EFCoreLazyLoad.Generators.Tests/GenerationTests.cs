    [Fact]
    public void NullableAndNonNullableNavigations_ProduceNoWarnings()
    {
        var result = GeneratorHarness.RunClean($$"""
            using System.Collections.Generic;
            using Rally25rs.EFCoreLazyLoad;
            {{RelatedTypes}}

            [LazyLoad]
            public partial class Customer
            {
                public partial Address Required { get; set; }
                public partial Address? Optional { get; set; }
                public partial List<Hobby> Hobbies { get; set; }
                public partial List<Hobby>? MaybeHobbies { get; set; }
                public partial IReadOnlyList<Hobby?> SparseHobbies { get; set; }
                public partial string Note { get; set; }
            }

            public static class Usage
            {
                // Non-nullable navigations must read as non-null at use sites.
                public static int Use(Customer c) => c.Required.Id + c.Hobbies.Count + c.Note.Length;
            }
            """);

        var source = result.GeneratedSource("Customer.LazyLoad.g.cs");
        Assert.Contains("ref field, nameof(Required))!;", source);
        Assert.Contains("ref field, nameof(Optional));", source);
        Assert.Contains("public partial global::System.Collections.Generic.List<global::Hobby>? MaybeHobbies", source);
    }

