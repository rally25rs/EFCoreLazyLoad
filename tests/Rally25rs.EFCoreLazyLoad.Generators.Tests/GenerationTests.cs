using Microsoft.CodeAnalysis;

namespace Rally25rs.EFCoreLazyLoad.Generators.Tests;

public class GenerationTests
{
    private const string RelatedTypes = """
        public class Address { public int Id { get; set; } }
        public class Hobby { public int Id { get; set; } }
        """;

    [Fact]
    public void ClassLevelAttribute_GeneratesExpectedCode()
    {
        var result = GeneratorHarness.RunClean($$"""
            using System.Collections.Generic;
            using Rally25rs.EFCoreLazyLoad;

            namespace Shop;

            {{RelatedTypes}}

            [LazyLoad]
            public partial class Customer
            {
                public int Id { get; set; }
                public partial Address Address { get; set; }
                public partial List<Hobby> Hobbies { get; set; }
            }
            """);

        Assert.Equal(
            """
            // <auto-generated/>
            #nullable enable

            namespace Shop;

            partial class Customer
            {
                [global::System.Text.Json.Serialization.JsonIgnore]
            #pragma warning disable CS0649
                protected global::Microsoft.EntityFrameworkCore.Infrastructure.ILazyLoader? __lazyLoader;
            #pragma warning restore CS0649

                public partial global::Shop.Address Address
                {
                    get => global::Microsoft.EntityFrameworkCore.Infrastructure.LazyLoaderExtensions.Load(__lazyLoader, this, ref field, nameof(Address))!;
                    set => field = value;
                }

                public partial global::System.Collections.Generic.List<global::Shop.Hobby> Hobbies
                {
                    get => global::Microsoft.EntityFrameworkCore.Infrastructure.LazyLoaderExtensions.Load(__lazyLoader, this, ref field, nameof(Hobbies))!;
                    set => field = value;
                }
            }

            """.ReplaceLineEndings(),
            result.GeneratedSource("Shop.Customer.LazyLoad.g.cs").ReplaceLineEndings());
    }

    [Fact]
    public void AttributeSettings_DoNotChangeGeneratedCode()
    {
        // Mode / LogLazyLoads / LogLevel are read at runtime; the generated code is identical with or without them.
        const string plain = $$"""
            using System.Collections.Generic;
            using Rally25rs.EFCoreLazyLoad;

            namespace Shop;

            {{RelatedTypes}}

            [LazyLoad]
            public partial class Customer
            {
                public partial Address Address { get; set; }
                public partial List<Hobby> Hobbies { get; set; }
            }
            """;
        const string withSettings = $$"""
            using System.Collections.Generic;
            using Microsoft.Extensions.Logging;
            using Rally25rs.EFCoreLazyLoad;

            namespace Shop;

            {{RelatedTypes}}

            [LazyLoad(Mode = LazyLoadMode.Throw, LogLazyLoads = true)]
            public partial class Customer
            {
                [LazyLoad(Mode = LazyLoadMode.Load, LogLevel = LogLevel.Information)]
                public partial Address Address { get; set; }
                public partial List<Hobby> Hobbies { get; set; }
            }
            """;

        var expected = GeneratorHarness.RunClean(plain).GeneratedSource("Shop.Customer.LazyLoad.g.cs");
        var actual = GeneratorHarness.RunClean(withSettings).GeneratedSource("Shop.Customer.LazyLoad.g.cs");

        Assert.Equal(expected, actual);
    }

    [Fact]
