    [Fact]
    public void Modifiers_AreCopied()
    {
        var result = GeneratorHarness.RunClean($$"""
            using Rally25rs.EFCoreLazyLoad;
            {{RelatedTypes}}

            public class EntityBase
            {
                public virtual Address? Overridden { get; set; }
                public Address? Hidden { get; set; }
            }

            [LazyLoad]
            public partial class Customer : EntityBase
            {
                public required partial Address Required { get; init; }
                protected internal virtual partial Address Virtual { get; private set; }
                internal partial Address GetOnly { get; }
                private partial Address? PrivateNav { get; set; }
                public override partial Address? Overridden { get; set; }
                public new partial Address? Hidden { get; protected set; }
                public sealed override string ToString() => PrivateNav?.ToString() ?? "";
            }
            """);

        var source = result.GeneratedSource("Customer.LazyLoad.g.cs");
        Assert.Contains("public required partial global::Address Required", source);
        Assert.Contains("init => field = value;", source);
        Assert.Contains("protected internal virtual partial global::Address Virtual", source);
        Assert.Contains("private set => field = value;", source);
        Assert.Contains("internal partial global::Address GetOnly", source);
        Assert.Contains("private partial global::Address? PrivateNav", source);
        Assert.Contains("public override partial global::Address? Overridden", source);
        Assert.Contains("public new partial global::Address? Hidden", source);
        Assert.Contains("protected set => field = value;", source);
    }

