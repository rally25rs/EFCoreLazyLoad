    [Fact]
    public void ClassLevel_IgnoresNonPartialAndImplementedProperties()
    {
        var result = GeneratorHarness.RunClean($$"""
            using Rally25rs.EFCoreLazyLoad;
            {{RelatedTypes}}

            [LazyLoad]
            public partial class Customer
            {
                public int Id { get; set; }
                public Address? Plain { get; set; }
                public partial Address? Manual { get; set; }
                public partial Address? Manual { get => field; set => field = value; }
                public partial Address Generated { get; set; }
            }
            """);

        var source = result.GeneratedSource("Customer.LazyLoad.g.cs");
        Assert.Contains("Generated", source);
        Assert.DoesNotContain("Plain", source);
        Assert.DoesNotContain("Manual", source);
    }
